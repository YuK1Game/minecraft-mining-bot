test('only an authoritative removal creates a bounded tombstone, cleared on reappearance or dimension change', () => {
  const tracker = createEntities({ limit: 2 })
  tracker.applyPacket('add_entity', { entity_type: 'minecraft:zombie', unique_id: 100n, runtime_id: 10n, position: { x: 1, y: 2, z: 3 } })
  assert.deepEqual(tracker.snapshotRemoved(), [])
  tracker.applyPacket('remove_entity', { entity_id_self: 100n })
  assert.deepEqual(tracker.snapshotRemoved().map(({ runtimeId, uniqueId, entityType }) => ({ runtimeId, uniqueId, entityType })), [{ runtimeId: '10', uniqueId: '100', entityType: 'minecraft:zombie' }])
  tracker.applyPacket('add_entity', { entity_type: 'minecraft:zombie', unique_id: 100n, runtime_id: 11n, position: { x: 2, y: 2, z: 3 } })
  assert.deepEqual(tracker.snapshotRemoved(), [])
  tracker.applyPacket('remove_entity', { entity_id_self: 100n })
  tracker.applyPacket('change_dimension', { dimension: 1 })
  assert.deepEqual(tracker.snapshotRemoved(), [])
})

