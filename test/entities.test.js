test('known hostile types are explicit, players are never hostile, and self identity excludes this player', () => {
  const tracker = createEntities()
  tracker.applyPacket('start_game', { runtime_entity_id: 41n, entity_id: 7n, dimension: 'overworld' })
  tracker.applyPacket('add_player', { runtime_id: 41n, unique_id: 7n, username: 'Self', position: { x: 0, y: 70, z: 0 } })
  tracker.applyPacket('add_player', { runtime_id: 42n, unique_id: 8n, username: 'minecraft:zombie', position: { x: 1, y: 70, z: 0 } })
  mob(tracker, 'minecraft:zombie', 9n, 43n)
  mob(tracker, 'minecraft:cow', 10n, 44n)
  mob(tracker, 'custom:zombie', 11n, 45n)
  assert.equal(tracker.snapshot({ kind: 'all' }).length, 4)
  assert.equal(tracker.snapshot({ kind: 'hostile' }).length, 1)
  assert.equal(tracker.snapshot({ kind: 'player' })[0].hostile, false)
  assert.equal(tracker.snapshot({ kind: 'mob' }).find(entity => entity.name === 'minecraft:cow').hostility, 'unclassified')
  assert.equal(tracker.snapshot({ kind: 'entity' })[0].hostile, false)
  assert.equal(tracker.snapshot().length, 0, 'legacy default remains dropped items only')
  tracker.setSelfRuntimeId('42')
  assert.equal(tracker.snapshot({ kind: 'player' }).length, 0)
})

