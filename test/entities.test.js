test('Bedrock creeper metadata tracks fuse, ignition and charge without treating unrelated updates as disarming', () => {
  const tracker = createEntities()
  tracker.applyPacket('add_entity', { entity_type: 'minecraft:creeper', unique_id: 3n, runtime_id: 13n, position: { x: 1, y: 69, z: 1 }, metadata: [{ key: 'flags', value: { ignited: false, powered: false, charged: false } }, { key: 'fuse_length', value: -1 }] })
  const current = () => tracker.snapshot({ kind: 'hostile' })[0]
  assert.equal(current().primed, false)
  assert.equal(threatRadius(current()), 8)
  tracker.applyPacket('set_entity_data', { runtime_entity_id: 13n, tick: 11n, metadata: [{ key: 'flags', value: { ignited: true, powered: false, charged: false } }, { key: 'fuse_length', value: 29 }] })
  assert.equal(current().primed, true)
  assert.equal(current().fuseLength, 29)
  assert.equal(threatRadius(current()), 12)
  tracker.applyPacket('entity_event', { runtime_entity_id: 13n, event_id: 'hurt_animation', data: 0 })
  tracker.applyPacket('set_entity_data', { runtime_entity_id: 13n, tick: 12n, metadata: [{ key: 'fuse_length', value: 27 }] })
  assert.equal(current().primed, true)
  tracker.applyPacket('set_entity_data', { runtime_entity_id: 13n, tick: 10n, metadata: [{ key: 'flags', value: { ignited: false, powered: false, charged: false } }, { key: 'fuse_length', value: -1 }] })
  assert.equal(current().primed, true, 'older metadata cannot cancel an active fuse')
  tracker.applyPacket('set_entity_data', { runtime_entity_id: 13n, tick: 13n, metadata: [{ key: 'flags', value: { ignited: false, powered: false, charged: false } }] })
  assert.equal(current().primed, false, 'a newer unlit flag can cancel the previously reported counter')
  tracker.applyPacket('set_entity_data', { runtime_entity_id: 13n, tick: 13n, metadata: [{ key: 'fuse_length', value: 27 }] })
  assert.equal(current().primed, true, 'a newer positive countdown can reveal ignition before a flags update')
  tracker.applyPacket('set_entity_data', { runtime_entity_id: 13n, tick: 13n, metadata: [{ key: 'fuse_length', value: -1 }] })
  assert.equal(current().primed, false)
  assert.equal(threatRadius(current()), 8)
  tracker.applyPacket('set_entity_data', { runtime_entity_id: 13n, tick: 14n, metadata: [{ key: 'flags', value: { ignited: false, powered: true, charged: false } }] })
  assert.equal(current().charged, true)
  assert.equal(threatRadius(current()), 16)
  tracker.applyPacket('remove_entity', { entity_id_self: 3n })
  assert.equal(tracker.snapshot({ kind: 'hostile' }).length, 0)
})

