const name={S:'minecraft:stone',O:'minecraft:stone',D:'minecraft:dirt','.':'minecraft:air',',':'minecraft:air',W:'minecraft:water'}
function read(x,y,z){
  let ch
  if(y<62) ch = x<=-4884 ? 'S' : 'W'
  else if(y>66) ch='.'
  else { const rows=grid[y].split('\n'); const zi=z+4931; if(zi<0) ch='S'; else if(zi>=rows.length) ch = y===62?'W':'.'; else { const xi=x+4888; ch = xi<0?'S': xi>=14 ? (y===62?'W':'.') : rows[zi][xi] } }
  const n=name[ch]
  return {known:true,position:{x,y,z},name:n,properties: n==='minecraft:water'?{liquid_depth:0}:{},boundingBox: (ch==='S'||ch==='O'||ch==='D')?'block':'empty',extra:[]}
}

test('a swimmer read a float32 hair inside the ledge face still climbs onto it', () => {
  const physics = createPhysics({ world: { getBlock: read }, allowWater: true })
  for (const y of [62.1, 62.47, 62.66]) {
    const initial = physics.fromServer({ position: { x: -4881.5, y: y + 1.62, z: Math.fround(-4924.7) }, gameMode: 'survival' })
    Object.assign(initial, { isInWater: true, onGround: false, velocity: { x: 0, y: 0, z: 0 } })
    const route = planWaterExit({ physics, initial, target: { x: -4881.5, y: 63, z: -4925.5 } })
    assert.equal(route.ready, true, `${y}: ${route.reason}`)
  }
})
